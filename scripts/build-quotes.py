#!/usr/bin/env python3
"""Build public/data/quotes.js: for each mapped place, the passage in each of its sources that best supports it,
taken from the copies already in our archive (CIA reading room / JPRS / FBIS texts, Wikipedia pages).
The reader in the place panel shows that passage with its key sentence highlighted, next to a link to the original.
Run from the repo root:  python3 scripts/build-quotes.py"""
import gzip, json, os, re, subprocess, urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
sites = json.loads(subprocess.check_output(['node', '-e', "global.window={};require('./public/data/sites.js');process.stdout.write(JSON.stringify(window.ATLAS_SITES))"]))

def norm(u):
    u = urllib.parse.unquote(u or '').strip().rstrip('/')
    u = re.sub(r'^https?://(www\.)?', '', u)
    return u.replace(' ', '_').lower()

wanted = {norm(x.get('u')) for s in sites for x in s.get('sources') or []}
texts = {}
def keep(url, title, date, text):
    k = norm(url)
    if k in wanted and text and k not in texts: texts[k] = {'t': title, 'd': date, 'text': text}

for f in ['archive/crest/docs.jsonl.gz', 'archive/crest/docs-other.jsonl.gz']:
    if not os.path.exists(f): continue
    for line in gzip.open(f, 'rt'):
        d = json.loads(line)
        for u in [d.get('cia'), d.get('ia'), d.get('url')]:
            if u: keep(u, d.get('title', ''), d.get('date', ''), d.get('text', ''))
for lang in ['en', 'ar']:
    p = 'archive/wikipedia/' + lang
    if not os.path.isdir(p): continue
    for fn in os.listdir(p):
        try: d = json.load(open(os.path.join(p, fn)))
        except Exception: continue
        keep(d.get('url', ''), d.get('title', ''), d.get('fetched', ''), d.get('text', ''))
# FBIS daily reports and government documents saved as text files, matched through their catalogs
for cat, folder in [('archive/fbis/catalog.json', 'archive/fbis'), ('archive/gov/catalog.json', 'archive/gov')]:
    if not os.path.exists(cat): continue
    try: items = json.load(open(cat))
    except Exception: continue
    for it in items if isinstance(items, list) else []:
        u = it.get('url') or ''
        if norm(u) not in wanted: continue
        for fn in os.listdir(folder):
            if it.get('identifier') and it['identifier'] in fn:
                keep(u, it.get('title', ''), it.get('date', ''), open(os.path.join(folder, fn), errors='ignore').read()); break

STOP = set('the and for with from that this were was are has had have its into after before over under about their there which while where when what who whom whose been being than then also only very more most some such other these those near said says city tripoli libya libyan gaddafi qadhafi'.split())
def words(s):
    return [w for w in re.findall(r"[A-Za-z؀-ۿ][A-Za-z؀-ۿ'\-]{2,}", s or '') if w.lower() not in STOP]

def best(site, text):
    text = re.sub(r'\s+', ' ', text)
    sents = re.split(r'(?<=[.!?؟])\s+(?=[A-Z0-9“"؀-ۿ(])', text)
    if len(sents) < 2: sents = [text[i:i + 300] for i in range(0, min(len(text), 60000), 300)]
    name = [w.lower() for w in words(site['name']) + words(site.get('ar', ''))]
    body = [w.lower() for w in words(site.get('relevance', '') + ' ' + site.get('text', ''))]
    years = {str(y) for y in [site.get('y0'), site.get('y1')] if y}
    nums = set(re.findall(r'\b\d{2,4}\b', site.get('text', '')))
    bw = {}
    for w in body: bw[w] = bw.get(w, 0) + 1
    top, ti = 0, -1
    for i, s in enumerate(sents[:4000]):
        if len(s) > 700: continue
        low = s.lower(); sc = 0
        for w in set(name):
            if w in low: sc += 4
        for w, c in bw.items():
            if len(w) > 4 and w in low: sc += min(c, 3) * 0.6
        for y in years:
            if y in s: sc += 2
        for n in nums:
            if n in s: sc += 1
        if sc > top: top, ti = sc, i
    if ti < 0 or top < 5: return None
    a, b = max(0, ti - 1), min(len(sents), ti + 2)
    pre, hi, post = ' '.join(sents[a:ti]), sents[ti], ' '.join(sents[ti + 1:b])
    if len(pre) > 320: pre = '…' + pre[-300:]
    if len(post) > 320: post = post[:300] + '…'
    return {'pre': pre, 'hi': hi, 'post': post}

out, n = {}, 0
for s in sites:
    for x in s.get('sources') or []:
        k = norm(x.get('u'))
        if k not in texts: continue
        q = best(s, texts[k]['text'])
        if not q: continue
        q['t'] = texts[k]['t']; q['d'] = texts[k]['d']
        out.setdefault(s['id'], {})[x['u']] = q; n += 1
with open('public/data/quotes.js', 'w') as f:
    f.write('/* Generated by scripts/build-quotes.py: the supporting passage from each archived source, per mapped place. */\n')
    f.write('window.ATLAS_QUOTES = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('sources with archived text:', len(texts), 'passages:', n, 'places:', len(out), 'bytes:', os.path.getsize('public/data/quotes.js'))
