"""Builds public/data/areas.js from archive/areas/areas_*.py (lists named AREAS)."""
import json, glob, os, runpy
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
areas, seen = [], set()
for f in sorted(glob.glob(os.path.join(ROOT, 'archive', 'areas', 'areas_*.py'))):
    for a in runpy.run_path(f)['AREAS']:
        assert a['id'] not in seen, a['id']; seen.add(a['id'])
        for k in ('id', 'name', 'kind', 'lat', 'lon', 'summary'): assert a.get(k) not in (None, ''), (a['id'], k)
        a = {k: v for k, v in a.items() if v not in (None, '', [])}
        areas.append(a)
# researched landmark batches (archive/areas/landmarks_batch_*.json): need coordinates inside Greater Tripoli; skip duplicates
import re
norm = lambda t: re.sub(r'[^a-z0-9\u0600-\u06ff]+', '', (t or '').lower())
names = {norm(n) for a in areas for n in [a['name']] + a.get('aliases', [])}
skipped = []
for f in sorted(glob.glob(os.path.join(ROOT, 'archive', 'areas', 'landmarks_batch_*.json'))):
    for a in json.load(open(f)):
        key = norm(a.get('name'))
        if a.get('id') in seen or key in names: skipped.append((a.get('name'), 'duplicate')); continue
        lat, lon = a.get('lat'), a.get('lon')
        if not (isinstance(lat, (int, float)) and isinstance(lon, (int, float)) and 32.55 <= lat <= 33.05 and 12.85 <= lon <= 13.55): skipped.append((a.get('name'), 'no coordinates')); continue
        if not a.get('summary'): skipped.append((a.get('name'), 'no summary')); continue
        a = {k: v for k, v in a.items() if v not in (None, '', []) and k not in ('category', 'built', 'period')}
        a['kind'] = a.get('kind') if a.get('kind') in ('landmark', 'government', 'prison') else 'landmark'
        seen.add(a['id']); names.add(key); areas.append(a)
if skipped: print('skipped', len(skipped), skipped[:40])
json.dump(areas, open(os.path.join(ROOT, 'archive', 'areas', 'areas.json'), 'w'), ensure_ascii=False, indent=1)
with open(os.path.join(ROOT, 'public', 'data', 'areas.js'), 'w') as fh:
    fh.write('/* Generated by scripts/build-areas.py from archive/areas/. Profiles of Tripoli neighbourhoods, military sites and landmarks. */\nwindow.ATLAS_AREAS = ' + json.dumps(areas, ensure_ascii=False) + ';\n')
print(len(areas), 'areas', {k: sum(1 for a in areas if a['kind'] == k) for k in set(a['kind'] for a in areas)})
