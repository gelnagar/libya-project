// F8: copy the web fonts the pages use into public/fonts/ so visitors' browsers never contact Google (PRD s9).
//   node scripts/self-host-fonts.mjs        (run once, or to add a font; needs the network; fonts are SIL Open Font License)
// Fetches Google's stylesheet for each family, keeps only the subsets the site needs (Latin, plus Arabic for Noto Sans Arabic),
// downloads the .woff2 files and writes public/fonts/fonts.css with local addresses.
import fs from 'node:fs'; import crypto from 'node:crypto';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const FAMILIES = [
  ['Inter', 'family=Inter:wght@400;500;600', ['latin']],
  ['JetBrains Mono', 'family=JetBrains+Mono:wght@400;500', ['latin']],
  ['Noto Sans Arabic', 'family=Noto+Sans+Arabic:wght@400;500;600', ['arabic']],
  ['IBM Plex Sans', 'family=IBM+Plex+Sans:wght@400;500;600', ['latin']],
  ['IBM Plex Mono', 'family=IBM+Plex+Mono:wght@400;500', ['latin']],
  ['Source Serif 4', 'family=Source+Serif+4:opsz,wght@8..60,500;8..60,700', ['latin']]
];
fs.mkdirSync('public/fonts', { recursive: true });
let css = '/* Generated by scripts/self-host-fonts.mjs. Fonts: SIL Open Font License 1.1 (Inter, JetBrains Mono, Noto Sans Arabic, IBM Plex, Source Serif). Do not hand-edit. */\n';
const have = new Map();
for (const [name, q, keep] of FAMILIES) {
  const r = await fetch('https://fonts.googleapis.com/css2?' + q + '&display=swap', { headers: { 'User-Agent': UA } });
  if (!r.ok) { console.error('FAILED', name, r.status); process.exit(1); }
  const text = await r.text();
  for (const m of text.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)) {
    if (!keep.includes(m[1])) continue;
    let block = m[2]; const url = /url\((https:[^)]+\.woff2)\)/.exec(block)[1];
    if (!have.has(url)) {
      const f = await fetch(url); const buf = Buffer.from(await f.arrayBuffer());
      const file = name.toLowerCase().replace(/[^a-z0-9]+/g, '-') + '-' + m[1] + '-' + crypto.createHash('sha256').update(buf).digest('hex').slice(0, 8) + '.woff2';
      fs.writeFileSync('public/fonts/' + file, buf); have.set(url, file); console.log('saved', file, buf.length);
    }
    css += block.replace(url, have.get(url)).replace(/url\(([^h)][^)]*)\)/, 'url($1)') + '\n';
  }
}
fs.writeFileSync('public/fonts/fonts.css', css); console.log('wrote public/fonts/fonts.css');
