// Merges archive/research/links.json + links-curated.json into public/data/links.js (dedupes by pair+kind).
import fs from 'fs';
const R = 'archive/research/';
const all = [...JSON.parse(fs.readFileSync(R + 'links.json')), ...JSON.parse(fs.readFileSync(R + 'links-curated.json')), ...(fs.existsSync(R + 'links-auto.json') ? JSON.parse(fs.readFileSync(R + 'links-auto.json')) : [])];
const seen = new Set(), out = [];
for (const l of all) { const k = [l.a, l.b].sort().join('|') + l.kind; if (seen.has(k)) continue; seen.add(k); out.push(l); }
fs.writeFileSync('public/data/links.js', '/* Evidence-based connections between places (archive/research/links.json + links-curated.json + links-auto.json from scripts/auto-links.py). Generated by scripts/build-links.mjs. */\nwindow.ATLAS_CONNECTIONS = ' + JSON.stringify(out) + ';\n');
console.log(out.length, 'connections');
