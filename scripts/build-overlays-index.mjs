// Writes public/data/overlays.js: the historical maps and satellite images the map can lay over Tripoli.
// Sources: archive/maps/overlays.json (scanned maps, tiled by build-overlays.sh) and public/maps/*/meta.json (Landsat).
import { readFile, writeFile, readdir, access } from 'node:fs/promises';
const ROOT = new URL('..', import.meta.url).pathname;
const exists = async (p) => { try { await access(ROOT + p); return true; } catch { return false; } };
const out = [];
for (const m of JSON.parse(await readFile(ROOT + 'archive/maps/overlays.json', 'utf8'))) {
  if (!(await exists(`public/maps/${m.id}/done`))) continue;
  let ext = null; try { ext = JSON.parse(await readFile(ROOT + `public/maps/${m.id}/extent.json`, 'utf8')); } catch {}
  const ring = ext && ext.coordinates ? ext.coordinates[0] : null;
  const lons = ring ? ring.map((p) => p[0]) : [m.bbox[0], m.bbox[2]], lats = ring ? ring.map((p) => p[1]) : [m.bbox[1], m.bbox[3]];
  const zmax = +String(m.zooms).split('-')[1], ts = m.tilesize || 256;
  const files = await readdir(ROOT + `public/maps/${m.id}/${zmax}`).catch(() => []);
  const sample = files.length ? (await readdir(ROOT + `public/maps/${m.id}/${zmax}/${files[0]}`))[0] : 'x.webp';
  out.push({ id: m.id, kind: m.kind || 'map', title: m.title, year: m.year, note: m.note || '', source: m.source, page: m.page, license: m.license,
    tiles: `maps/${m.id}/{z}/{x}/{y}.` + sample.split('.').pop(),
    ...(ts === 512 ? { tileSize: 512, zoomOffset: -1 } : {}),
    ...((ts === 512 ? files.length > 0 : (zmax < 17 && (await exists(`public/maps/${m.id}/17`)))) ? { tilesHi: `maps/${m.id}/{z}/{x}/{y}.` + sample.split('.').pop() } : {}), bounds: [[Math.min(...lats), Math.min(...lons)], [Math.max(...lats), Math.max(...lons)]], maxZoom: zmax,
    attribution: `${m.title.split('(')[0].trim()} — ${m.source}` });
}
for (const d of (await readdir(ROOT + 'public/maps').catch(() => [])).sort()) {
  if (!d.startsWith('landsat-') || !(await exists(`public/maps/${d}/meta.json`))) continue;
  const m = JSON.parse(await readFile(ROOT + `public/maps/${d}/meta.json`, 'utf8'));
  out.push({ id: m.id, kind: 'satellite', title: `Satellite, ${m.date.slice(0, 4)}`, year: +m.date.slice(0, 4), note: `${m.note}. Taken ${m.date}. About 30 m detail${m.id.includes('1970') ? ' (60 m)' : ''}: it shows how far the city had spread, not individual buildings.`, source: m.source, license: m.license,
    tiles: `maps/${m.id}/{z}/{x}/{y}.${m.ext || 'png'}`, bounds: [[m.bbox[1], m.bbox[0]], [m.bbox[3], m.bbox[2]]], maxZoom: m.maxZoom, attribution: `Landsat ${m.date.slice(0, 4)} (USGS)` });
}
out.sort((a, b) => a.year - b.year);
await writeFile(ROOT + 'public/data/overlays.js', '/* Generated by scripts/build-overlays-index.mjs. Historical maps and satellite images. */\nwindow.ATLAS_OVERLAYS = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(out.map((o) => o.id + ' ' + o.year).join(', ') || 'none yet');
